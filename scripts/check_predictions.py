import pickle
import argparse

"""
This script loads the results from a pickle file generated by mmdetection and checks if any bounding boxes were predicted.

Purpose:
---------
The purpose of this script is to:
1. Load the pickle file containing model predictions.
2. Verify if any bounding boxes were predicted for each image.
3. Print the number of predicted bounding boxes for each image.

Usage:
------
1. Ensure you have the pickle file containing the results from your model's inference.
2. Run the script with the following command:
   python check_predictions.py --results_file path/to/results.pkl

Arguments:
----------
--results_file: Path to the output pickle file containing results.

Example:
--------
python check_predictions.py --results_file results.pkl
"""

def parse_args():
    parser = argparse.ArgumentParser(description='Check if bounding boxes were predicted in the results file.')
    parser.add_argument('--results_file', required=True, help='Path to the output pickle file containing results')
    return parser.parse_args()

def load_results(results_file):
    with open(results_file, 'rb') as f:
        results = pickle.load(f)
    return results

def check_predictions(results):
    for i, image_info in enumerate(results):
        img_id = image_info.get('img_id', 'unknown')
        pred_bboxes = image_info['pred_instances']['bboxes'].numpy()
        print(f"Image ID: {img_id}, Number of predicted bounding boxes: {len(pred_bboxes)}")
        if len(pred_bboxes) == 0:
            print(f"No predictions for image {img_id}")

if __name__ == "__main__":
    args = parse_args()
    results = load_results(args.results_file)
    check_predictions(results)
